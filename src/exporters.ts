import type { PromptVariant } from './domain';

function safePrompt(prompt: string): string {
  return prompt.replace(/\\/g, '\\\\').replace(/`/g, '\\`');
}

export function exportJson(variant: PromptVariant): string {
  // JSON is the portable contract consumed by the Android and Apple clients.
  return JSON.stringify({
    schema: 'prompt-project-variant/v1',
    exportedAt: new Date().toISOString(),
    ...variant,
  }, null, 2);
}

